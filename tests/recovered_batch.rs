use mspaint_port::recovered::{accessors::*, captures, interfaces, text};
use std::collections::BTreeSet;

fn hex(value: &str) -> u64 {
    u64::from_str_radix(value.trim_start_matches("0x"), 16).unwrap()
}

fn bytes(value: &str) -> Vec<u8> {
    value
        .as_bytes()
        .as_chunks::<2>()
        .0
        .iter()
        .map(|pair| u8::from_str_radix(std::str::from_utf8(pair).unwrap(), 16).unwrap())
        .collect()
}

fn word32(record: &[u8]) -> u32 {
    u32::from_le_bytes(record[..4].try_into().unwrap())
}
fn word64(record: &[u8]) -> u64 {
    u64::from_le_bytes(record[..8].try_into().unwrap())
}

// Adapt the original function's typed pointer arguments into the safe Rust
// interfaces. Return-pointer identity is represented by one for these setters;
// the references are caller-owned and setters cannot replace them.
fn accessor(name: &str, source: &mut [u8], destination: &mut [u8], argument: u64) -> u64 {
    match name {
        "FUN_140001b50" => {
            let mut word = word32(destination);
            fun_140001b50(&mut word, argument as u32);
            destination[..4].copy_from_slice(&word.to_le_bytes());
            1
        }
        "FUN_140002190" => u64::from(fun_140002190(&word32(source))),
        "FUN_1400069f0" => {
            let mut word = word32(destination);
            fun_1400069f0(source, &mut word).unwrap();
            destination[..4].copy_from_slice(&word.to_le_bytes());
            1
        }
        "FUN_1400095b0" => {
            let mut word = word32(destination);
            let result = fun_1400095b0(&mut word);
            destination[..4].copy_from_slice(&word.to_le_bytes());
            result
        }
        "FUN_14000a870" => {
            let mut word = word64(destination);
            fun_14000a870(&mut word);
            destination[..8].copy_from_slice(&word.to_le_bytes());
            1
        }
        "FUN_1400122b0" => u64::from(fun_1400122b0(argument as u32)),
        "FUN_140018e70" => {
            fun_140018e70(destination, argument as u32, argument).unwrap();
            1
        }
        "FUN_140024c50" => {
            fun_140024c50(destination).unwrap();
            1
        }
        "FUN_140031740" => u64::from(fun_140031740(source).unwrap()),
        "FUN_140031750" => u64::from(fun_140031750(source).unwrap()),
        "FUN_14003b150" => u64::from(fun_14003b150(source).unwrap()),
        "FUN_14003b1a0" => fun_14003b1a0(&word64(source)),
        "FUN_14003c7a0" => fun_14003c7a0(source).unwrap() as u64,
        "FUN_140051b60" => fun_140051b60(source).unwrap(),
        "FUN_140052360" => u64::from(fun_140052360(source).unwrap()),
        "FUN_140066450" => fun_140066450(source).unwrap(),
        "FUN_140066ee0" => {
            fun_140066ee0(source, argument as u32).unwrap();
            0
        }
        "FUN_140066f00" => u64::from(fun_140066f00(source).unwrap()),
        "FUN_140069e90" => u64::from(fun_140069e90(source).unwrap()),
        "FUN_14009bd50" => {
            fun_14009bd50(source, argument as i32).unwrap();
            0
        }
        "FUN_14009bd60" => {
            fun_14009bd60(source, argument as i32).unwrap();
            0
        }
        "FUN_14007c280" => u64::from(fun_14007c280(source).unwrap()),
        "FUN_14007c290" => u64::from(fun_14007c290(source).unwrap()),
        "FUN_14007c2a0" => u64::from(fun_14007c2a0(source).unwrap()),
        "FUN_14007c2b0" => u64::from(fun_14007c2b0(source).unwrap()),
        "FUN_14007c2c0" => u64::from(fun_14007c2c0(source).unwrap()),
        "FUN_14007c2d0" => u64::from(fun_14007c2d0(source).unwrap()),
        _ => panic!("unrecognized accessor {name}"),
    }
}

#[test]
fn all_100_functions_match_the_original_c_reference() {
    // Generated by compiling the ORIGINAL selected C function bodies with TCC.
    // The only substituted symbol is an explicit test vtable relocation.
    let fixture = include_str!("fixtures/batch-001.csv");
    let mut covered = BTreeSet::new();
    let mut cases = 0;
    for line in fixture.lines() {
        let fields: Vec<&str> = line.split(',').collect();
        let name = fields[1];
        covered.insert(name);
        match fields[0] {
            "I" => {
                let (_, resolve) = interfaces::RESOLVERS
                    .iter()
                    .find(|entry| entry.0 == name)
                    .unwrap();
                assert_eq!(
                    resolve(hex(fields[2]), [hex(fields[3]), hex(fields[4])]),
                    hex(fields[5]),
                    "{line}"
                );
            }
            "C" => {
                let seed: usize = fields[2].parse().unwrap();
                let mut source: Vec<u8> = (0..64)
                    .map(|index| (index * 17 + seed * 31) as u8)
                    .collect();
                let mut destination = vec![(0xa5 + seed) as u8; 64];
                let (_, _, _, construct) = captures::CONSTRUCTORS
                    .iter()
                    .find(|entry| entry.0 == name)
                    .unwrap();
                construct(&mut source, &mut destination, 0x1234_5678_9abc_def0).unwrap();
                assert_eq!(source, bytes(fields[3]), "source of {name}, seed {seed}");
                assert_eq!(
                    destination,
                    bytes(fields[4]),
                    "destination of {name}, seed {seed}"
                );
            }
            "A" => {
                let seed: usize = fields[2].parse().unwrap();
                let mut source: Vec<u8> = (0..384)
                    .map(|index| (index * 17 + seed * 31) as u8)
                    .collect();
                let mut destination = vec![(0xa5 + seed) as u8; 384];
                let result = accessor(name, &mut source, &mut destination, hex(fields[3]));
                assert_eq!(result, hex(fields[4]), "result of {name}, seed {seed}");
                assert_eq!(source, bytes(fields[5]), "source of {name}, seed {seed}");
                assert_eq!(
                    destination,
                    bytes(fields[6]),
                    "destination of {name}, seed {seed}"
                );
            }
            "U" => {
                let units = [hex(fields[2]) as u16, hex(fields[3]) as u16];
                let count: usize = fields[4].parse().unwrap();
                let decoded = text::fun_14002c790(&units[..count]).unwrap();
                assert_eq!(
                    decoded.consumed,
                    fields[5].parse::<usize>().unwrap(),
                    "{line}"
                );
                assert_eq!(decoded.codepoint, hex(fields[6]) as u32, "{line}");
                assert_eq!(decoded.valid, fields[7] == "1", "{line}");
            }
            "P" => {
                assert_eq!(
                    fun_14005dbb0([hex(fields[2]), hex(fields[3]), hex(fields[4])]),
                    hex(fields[5]),
                    "{line}"
                );
            }
            "R" => {
                let path: Vec<u16> = fields[2]
                    .as_bytes()
                    .as_chunks::<4>()
                    .0
                    .iter()
                    .map(|unit| hex(std::str::from_utf8(unit).unwrap()) as u16)
                    .collect();
                assert_eq!(
                    text::fun_140019de0(&path),
                    fields[3].parse::<usize>().unwrap(),
                    "{line}"
                );
            }
            _ => panic!("unrecognized reference record {line}"),
        }
        cases += 1;
    }
    assert_eq!(cases, 9936);
    assert_eq!(
        covered.len(),
        100,
        "every additional function must be exercised"
    );
    let manifest = include_str!("../translations/batch-001.json");
    assert_eq!(manifest.matches("\"original\":").count(), 100);
    for name in covered {
        assert!(manifest.contains(&format!("\"original\": \"{name}\"")));
    }
    for previous in [
        "FUN_14000a540",
        "FUN_140012f40",
        "FUN_1400131e0",
        "FUN_140024720",
        "FUN_1400684b0",
        "FUN_140024810",
        "FUN_140011f10",
        "FUN_140030bf0",
        "FUN_14002f170",
        "FUN_14002f250",
        "FUN_14002f2f0",
        "FUN_140030c60",
        "FUN_140030d70",
        "FUN_140030e10",
        "FUN_140068590",
    ] {
        assert!(
            !manifest.contains(previous),
            "batch includes previously translated {previous}"
        );
    }
}

#[test]
fn capture_errors_do_not_partially_move_or_overwrite_records() {
    for &(name, required_source, required_destination, construct) in captures::CONSTRUCTORS {
        for available in 0..required_source {
            let mut source = vec![0x5a; available];
            let mut destination = vec![0xa5; required_destination];
            assert!(
                construct(&mut source, &mut destination, 7).is_err(),
                "{name}"
            );
            assert!(source.iter().all(|&byte| byte == 0x5a));
            assert!(destination.iter().all(|&byte| byte == 0xa5));
        }
        for available in 0..required_destination {
            let mut source = vec![0x5a; required_source];
            let mut destination = vec![0xa5; available];
            assert!(
                construct(&mut source, &mut destination, 7).is_err(),
                "{name}"
            );
            assert!(source.iter().all(|&byte| byte == 0x5a));
            assert!(destination.iter().all(|&byte| byte == 0xa5));
        }
    }
}

#[test]
fn accessors_reject_short_records_before_mutation() {
    let mut output = 123;
    assert!(fun_1400069f0(&[0; 15], &mut output).is_err());
    assert_eq!(output, 123);
    let mut record = [0xa5; 15];
    assert!(fun_140018e70(&mut record, 0, 0).is_err());
    assert!(fun_140024c50(&mut record).is_err());
    assert_eq!(record, [0xa5; 15]);
    assert!(fun_140031740(&[0; 25]).is_err());
    assert!(fun_140031750(&[0; 27]).is_err());
    assert!(fun_14003b150(&[0; 23]).is_err());
    assert!(fun_14003c7a0(&[0; 31]).is_err());
    assert!(fun_140051b60(&[0; 79]).is_err());
    assert!(fun_140052360(&[0; 209]).is_err());
    assert!(fun_140066450(&[0; 23]).is_err());
    let mut record = [0xa5; 147];
    assert!(fun_140066ee0(&mut record, 0).is_err());
    assert_eq!(record, [0xa5; 147]);
    assert!(fun_140066f00(&record).is_err());
    assert!(fun_140069e90(&[0; 363]).is_err());
    assert!(fun_14009bd50(&mut [0; 64], 1).is_err());
    assert!(fun_14009bd60(&mut [0; 65], 1).is_err());
    for getter in [
        fun_14007c280,
        fun_14007c290,
        fun_14007c2a0,
        fun_14007c2b0,
        fun_14007c2c0,
        fun_14007c2d0,
    ] {
        assert!(getter(&[0; 335]).is_err());
    }
}

#[test]
fn utf16_empty_and_path_prefix_examples() {
    assert_eq!(text::fun_14002c790(&[]), None);
    for (path, expected) in [
        ("", 0),
        ("C:", 2),
        ("c:/paint", 2),
        ("\\\\server\\share", 8),
        ("\\\\?\\C:\\paint", 3),
        ("\\\\.\\device", 3),
        ("/paint", 0),
    ] {
        let units: Vec<u16> = path.encode_utf16().collect();
        assert_eq!(text::fun_140019de0(&units), expected, "{path}");
    }
}
